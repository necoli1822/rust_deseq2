# usage: Rscript validation/gen_formula_cases.R src/glm/formula_r_cases.rs
# Writes Rust test data: model.matrix() column names, DESeq2 resultsNames and values
# for formula constructs, from R 4.5.3 / DESeq2 1.50.2
suppressMessages({library(DESeq2); library(splines)})
out <- commandArgs(TRUE)[1]
set.seed(1)
cd <- data.frame(cond = factor(rep(c("A", "B", "C"), each = 4)), batch = factor(rep(c("b1", "b2"), 6)),
                 x = round(as.vector(scale(rnorm(12))), 3), age = round(runif(12, 20, 60), 1),
                 dose = rep(c(1, 2, 3), 4),
                 geno = factor(rep(c("wild type", "KO-2", "1x"), 4)),
                 flag = rep(c(TRUE, FALSE), each = 6))
cd[["my var"]] <- factor(rep(c("p", "q"), each = 6))
fs <- c("~ factor(dose)", "~ as.factor(dose)", "~ factor(cond)", "~ batch + factor(dose)", "~ relevel(cond, ref = \"B\")",
        "~ relevel(cond, \"C\")", "~ relevel(factor(dose), \"2\")", "~ batch + relevel(cond, ref='B')", "~ relevel(cond, 3)",
        "~ as.numeric(x)", "~ as.integer(dose)", "~ as.numeric(cond)", "~ log(age)", "~ log2(age)", "~ log10(age)",
        "~ log1p(age)", "~ exp(x)", "~ expm1(x)", "~ sqrt(age)", "~ abs(x)", "~ scale(age)", "~ scale(age, center = FALSE)",
        "~ scale(age, scale=FALSE)", "~ scale(age, TRUE, FALSE)", "~ scale(age, center = 40, scale = 10)", "~ I(x^2)",
        "~ x + I(x^2)", "~ I(age/10)", "~ I((x+1)*2)", "~ I(x - 1)", "~ I(-x)", "~ I(2^x)", "~ I(x*age)", "~ I(1e5*x)",
        "~ I(0.0001*x)", "~ I(x %% 0.3)", "~ I(x %/% 0.3)", "~ poly(x, 2)", "~ poly(x, degree = 2, raw = TRUE)",
        "~ poly(x, 3)", "~ poly(x, 1)", "~ cond + poly(x,2)", "~ poly(age, 2)", "~ poly(cond, 2)", "~ ns(x, df=3)",
        "~ splines::ns(x, df = 3)", "~ ns(x, knots = c(-0.5, 0.5))", "~ ns(x, df = 4, intercept = TRUE) - 1",
        "~ ns(age, df = 2)", "~ ns(x)", "~ ns(x, 2)", "~ ns(x, df = 5)", "~ ns(x, d = 3)",
        "~ ns(x, df = 3, Boundary.knots = c(-1, 1))", "~ bs(x, df=4)", "~ bs(x, degree=2, df=3)", "~ bs(x)",
        "~ bs(x, knots = 0)", "~ bs(x, df = 6, intercept = TRUE) - 1", "~ bs(x, degree = 1, df = 3)",
        "~ bs(x, df = 4, Boundary.knots = c(-1, 1))", "~ splines::bs(age, df = 5)", "~ cond * poly(x, 2)",
        "~ cond:ns(x, df=2)", "~ ordered(cond)", "~ batch + ordered(dose)", "~ 0 + ordered(cond)", "~ ordered(cond):batch",
        "~ ordered(dose, levels = c(3, 1, 2))", "~ cond + offset(x)", "~ cond + offset(log(age))", "~ geno", "~ `my var`",
        "~ flag", "~ flag + cond", "~ flag:cond", "~ x - 1", "~ 0 + x + age", "~ x + age", "~ log(age):cond",
        "~ cond + log(age) + cond:log(age)", "~ cond + log( age )", "~ log(age) + log(age)", "~ factor(dose):cond",
        "~ I(cond == 'B')", "~ cond + I(x > 0)", "~ 0 + factor(dose)", "~ 0 + relevel(cond, 'B')", "~ log(age, 2)",
        "~ log(age, base = 2)", "~ log(age, 3)", "~ factor(flag)", "~ factor(geno)", "~ relevel(geno, ref = \"wild type\")",
        "~ factor(dose, levels = c(3, 1, 2))", "~ factor(cond, levels = c('C','B','A'))",
        "~ factor(cond, labels = c(\"a\", \"b\", \"c\"))", "~ factor(dose, labels = c(\"lo\", \"mid\", \"mid\"))",
        "~ poly(x, 2) + I(x^3)", "~ exp(-x)", "~ I(x^-1)", "~ I(+x)", "~ sqrt(abs(x))", "~ x:poly(age, 2)", "~ I(cond)",
        "~ as.character(dose)", "~ ordered(cond) + poly(x, 2) * batch + ns(age, df = 2):cond",
        "~ 0 + ordered(dose):x + I(x^2)", "~ (cond + batch)^2", "~ cond/batch", "~ I(x > 0 & age > 30)", "~ I(!flag)",
        "~ I(dose %in% c(1, 3))", "~ batch * poly(age, 2) - poly(age, 2)", "~ as.ordered(cond)", "~ stats::poly(x, 2)",
        "~ base::log(age)", "~ 1 + x:cond + cond", "~ scale(x) + batch:scale(age)", "~ as.double(dose)",
        "~ ns(x, df = 3.5)", "~ bs(x, df = 5.5)", "~ (cond + batch)^2.7", "~ poly(x, 2.5)")
rs <- function(s) paste0("\"", gsub("\"", "\\\\\"", s), "\"")
num <- function(v) paste(ifelse(v == 0, "0.0", sprintf("%.17e", v)), collapse = ", ")
lines <- c("// Generated by validation/gen_formula_cases.R (R 4.5.3, DESeq2 1.50.2): formula, colnames(model.matrix()) joined by '|',",
           "// resultsNames joined by ',', and the model matrix column by column",
           "pub(super) const R_CASES: &[(&str, &str, &str, &[f64])] = &[")
for (f in fs) {
  ff <- as.formula(f)
  mm <- suppressWarnings(model.matrix(ff, cd))
  nm <- colnames(mm); nm[nm == "(Intercept)"] <- "Intercept"; nm <- make.names(nm)
  if (attr(terms(ff), "intercept") == 1) {
    cn <- DESeq2:::renameModelMatrixColumns(cd, ff)
    cn <- cn[cn$from %in% nm, , drop = FALSE]
    nm[match(cn$from, nm)] <- cn$to
  }
  lines <- c(lines, sprintf("    (%s, %s, %s, &[%s]),", rs(f), rs(paste(colnames(mm), collapse = "|")),
                            rs(paste(nm, collapse = ",")), num(as.vector(mm))))
}
lines <- c(lines, "];")
errs <- c("~ log(cond)", "~ relevel(x, 1)", "~ relevel(cond, 'Z')", "~ relevel(ordered(cond), 'B')", "~ myfun(x)",
          "~ log(x)", "~ poly(x, 2, raw = T)", "~ .", "~ . - batch", "~ poly(x, 12)", "~ I(cond + 1)", "~ sqrt(cond)",
          "~ I(x * c(1, 2, 3, 4, 5))", "~ ns(cond)", "~ relevel(cond, ref = 4)", "~ I(1/0 * x)",
          "~ (cond + batch)^1")
lines <- c(lines, "// formulas whose model matrix R cannot build (an error, a NaN/Inf, or a variable not in colData)",
           "pub(super) const R_ERRORS: &[(&str, &str)] = &[")
for (f in errs) {
  ff <- as.formula(f)
  msg <- tryCatch({
    v <- all.vars(ff); if (!all(v %in% names(cd))) stop("all variables in design formula must be columns in colData")
    mm <- model.matrix(ff, cd)
    if (nrow(mm) < nrow(cd) || any(!is.finite(mm))) "NA or non-finite values" else "NO ERROR"
  }, error = function(e) conditionMessage(e), warning = function(w) conditionMessage(w))
  lines <- c(lines, sprintf("    (%s, %s),", rs(f), rs(gsub("\n", " ", msg))))
}
lines <- c(lines, "];")
writeLines(lines, out)
